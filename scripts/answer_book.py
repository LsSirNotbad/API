def save_answer(content):
    conn = pymysql.connect(**db_config)
    cur = conn.cursor()
    sql = """
    INSERT INTO answer_book(content)
    VALUES (%s)
    ON DUPLICATE KEY UPDATE id=id
    """
    try:
        cur.execute(sql, (content))
        conn.commit()
        if cur.rowcount == 1:
            print(f"✅新增：{content}")
        else:
            print(f"⏭重复跳过：{content}")
    except Exception as e:
        print(f"❌入库失败：{e}")
    finally:
        cur.close()
        conn.close()

